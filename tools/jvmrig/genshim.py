#!/usr/bin/env python3
# SPDX-License-Identifier: AGPL-3.0-or-later
# JVM rig shim generator (docs/agent-tasks/jvm-test-rig.md, item 2):
# scan the api-impl tree for `native` method declarations and emit JNI
# recording stubs (log "RIG-NATIVE <symbol>" to stderr, return the type's
# zero value) so tests that touch native seams run headlessly without
# hand-writing one shim per method. Hand-written real semantics belong in
# tools/jvmrig/shim.c; this file only generates recording stubs.
# Natives declared in *inner* classes get the file's top-level class name
# (wrong symbol => stays unresolved => same as no shim, never wrong data).
import re, sys, pathlib

COMMENT_BLOCK = re.compile(r'/\*.*?\*/', re.S)
COMMENT_LINE = re.compile(r'//[^\n]*')
DECL = re.compile(
    r'(?P<mods>(?:(?:public|private|protected|static|final|synchronized|'
    r'strictfp|transient|volatile)\s+)*)'
    r'native\s+(?P<ret>[A-Za-z_][\w.]*(?:\s*\[\s*\])*)\s+'
    r'(?P<name>\w+)\s*\((?P<args>[^)]*)\)\s*;')

PRIM = {'boolean': 'Z', 'byte': 'B', 'char': 'C', 'short': 'S', 'int': 'I',
        'long': 'J', 'float': 'F', 'double': 'D', 'void': 'V'}
JT = {'boolean': 'jboolean', 'byte': 'jbyte', 'char': 'jchar', 'short': 'jshort',
      'int': 'jint', 'long': 'jlong', 'float': 'jfloat', 'double': 'jdouble'}
DEF = {'boolean': 'JNI_FALSE', 'byte': '0', 'char': '0', 'short': '0', 'int': '0',
       'long': '0L', 'float': '0', 'double': '0', 'void': None}

def jescape(s):
    return s.replace('_', '_1').replace('$', '_00024')

def desc_escape(d):
    # JNI long-form mangling: '_' -> _1, '[' -> _3, ';' -> _, and any other
    # non-alphanumeric (e.g. '/' in Ljava/lang/String;) -> _<4 hex>.
    d = d.replace('_', '_1').replace('[', '_3').replace(';', '_')
    return re.sub(r'[^A-Za-z0-9_]', lambda m: '_%04x' % ord(m.group(0)), d)

def base_desc(t, pkg, imports):
    if t in PRIM:
        return PRIM[t]
    if t == 'String':
        return 'Ljava/lang/String;'
    if t == 'Object':
        return 'Ljava/lang/Object;'
    fq = imports.get(t) or (pkg + '.' + t if '.' not in t else t)
    return 'L' + fq.replace('.', '/') + ';'

def arg_desc(t, pkg, imports):
    t = t.replace(' ', '')
    arr = 0
    while t.endswith('[]'):
        arr += 1; t = t[:-2]
    if t.endswith('...'):
        arr += 1; t = t[:-3]
    return '[' * arr + base_desc(t.split('<')[0], pkg, imports)

def split_args(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch == '<': depth += 1
        if ch == '>': depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip()); cur = ''
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out

def arg_type(a):
    a = re.sub(r'\bfinal\s+', '', a).strip()
    if not a:
        return None
    parts = a.rsplit(None, 1)
    if len(parts) == 1:
        return parts[0]
    return parts[0] + ' ' + parts[1] if parts[1] == '[]' else parts[0]

def jtype(t):
    t = t.replace(' ', '')
    if t.endswith('[]') or t.endswith('...'):
        return 'jobjectArray'
    return JT.get(t.split('<')[0], 'jobject')

def collect(tree):
    decls = []
    for p in sorted(tree.rglob('*.java')):
        src = COMMENT_LINE.sub('', COMMENT_BLOCK.sub('',
              p.read_text(encoding='utf-8', errors='replace')))
        pm = re.search(r'\bpackage\s+([\w.]+)\s*;', src)
        pkg = pm.group(1) if pm else ''
        imports = {im.group(1).rsplit('.', 1)[-1]: im.group(1)
                   for im in re.finditer(r'\bimport\s+(?:static\s+)?([\w.]+)\s*;', src)}
        cls = p.stem
        for m in DECL.finditer(src):
            args = [t for t in (arg_type(a) for a in split_args(m.group('args'))) if t]
            decls.append({
                'pkg': pkg, 'cls': cls, 'name': m.group('name'),
                'ret': m.group('ret').replace(' ', ''),
                'descs': [arg_desc(t, pkg, imports) for t in args],
                'jargs': [jtype(t) for t in args],
            })
    return decls

def main():
    tree, out = pathlib.Path(sys.argv[1]), sys.argv[2]
    decls = collect(tree)
    overloads = {}
    for d in decls:
        overloads.setdefault((d['pkg'], d['cls'], d['name']), 0)
        overloads[(d['pkg'], d['cls'], d['name'])] += 1
    lines = ['/* generated by tools/jvmrig/genshim.py — recording stubs only */',
             '#include <jni.h>', '#include <stdio.h>', '']
    syms, n = set(), 0
    for d in decls:
        base = '_'.join(jescape(s) for s in d['pkg'].split('.')) \
               + '_' + jescape(d['cls']) + '_' + jescape(d['name'])
        sym = 'Java_' + base
        if overloads[(d['pkg'], d['cls'], d['name'])] > 1:
            sym += '__' + desc_escape(''.join(d['descs']))
        if sym in syms:
            continue
        syms.add(sym)
        ret = d['ret']
        cret = JT.get(ret, 'jobjectArray' if ret.endswith('[]') else 'jobject') \
               if ret != 'void' else 'void'
        params = ['JNIEnv *env', 'jobject self'] + [f'{jt} a{i}' for i, jt in enumerate(d['jargs'])]
        body = [f'JNIEXPORT {cret} JNICALL {sym}({", ".join(params)}) {{',
                f'  fprintf(stderr, "RIG-NATIVE {sym}\\n");']
        if ret == 'void':
            body.append('}')
        else:
            default = DEF.get(ret, 'NULL')
            body.append(f'  return {default};')
            body.append('}')
        lines.append('\n'.join(body))
        n += 1
    with open(out, 'w') as f:
        f.write('\n\n'.join(lines) + '\n')
    print(f'genshim: {n} recording stubs -> {out}')

if __name__ == '__main__':
    main()
